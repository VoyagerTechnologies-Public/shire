"""DTN settings: the dtn: block, the generated CMake file, and which startup entries a spacecraft keeps."""
import unittest

from shire_dtn_config import MAX_NODE_ID, normalize_dtn, prune_startup_script, render_dtn_cmake

SCRIPT = [
    "CFE_LIB, cryptolib,   Crypto_SC_Init,     CRYPTOLIB,     0,       0, 0x0, 0;\n",
    "CFE_LIB, io_lib,      IO_LibInit,         IO_LIB,        0,       0, 0x0, 0;\n",
    "CFE_LIB, bplib,       BPLib_PrintVersion, BP_LIB,        0,       0, 0x0, 0;\n",
    "\n",
    "CFE_APP, cf,          CF_AppMain,         CF,           40,   32768, 0x0, 0;\n",
    "CFE_APP, bpnode,      BPNode_AppMain,     BPNODE,       45,   16384, 0x0, 0;\n",
    "CFE_APP, adcs,        ADCS_AppMain,       ADCS_APP,     60,    8192, 0x0, 0;\n",
    "CFE_APP, demo,        DEMO_AppMain,       DEMO_APP,     61,    8192, 0x0, 0;\n",
    "CFE_APP, radio,       RADIO_AppMain,      RADIO_APP,    63,   32768, 0x0, 0;\n",
    "!\n",
    "! A comment that mentions bpnode and adcs.\n",
]


def names(lines):
    return [line.split(",")[1].strip() for line in lines if line.startswith("CFE_")]


class NormalizeDtnTests(unittest.TestCase):
    def test_no_block_means_no_bundle_protocol(self):
        self.assertIsNone(normalize_dtn(None))

    def test_a_node_id_is_the_only_setting(self):
        self.assertEqual(normalize_dtn({"node_id": 101}), {"node_id": 101})
        self.assertEqual(normalize_dtn({"node_id": MAX_NODE_ID}), {"node_id": MAX_NODE_ID})

    def test_bad_blocks_are_rejected(self):
        for bad in ({}, {"node_id": 0}, {"node_id": -1}, {"node_id": MAX_NODE_ID + 1}, {"node_id": True},
                    {"node_id": "5"}, {"node_id": 1.5}):
            with self.subTest(block=bad), self.assertRaisesRegex(ValueError, "dtn node_id must be an integer"):
                normalize_dtn(bad)
        with self.assertRaisesRegex(ValueError, "unknown key.*'nodeid'"):
            normalize_dtn({"node_id": 1, "nodeid": 2})
        with self.assertRaisesRegex(ValueError, "must be a mapping"):
            normalize_dtn([101])


class RenderTests(unittest.TestCase):
    def test_the_node_number_becomes_a_compile_definition(self):
        text = render_dtn_cmake({"node_id": 100})
        self.assertIn("add_compile_definitions(BPLIB_LOCAL_EID_NODE_NUM=100)", text)
        self.assertTrue(text.startswith("# Generated by tools/shire-orchestrator.py"))
        self.assertTrue(text.endswith("\n"))


class PruneStartupScriptTests(unittest.TestCase):
    ALL = {"adcs", "demo", "eps", "radio"}

    def test_a_spacecraft_with_dtn_keeps_bpnode_and_its_library(self):
        kept, removed = prune_startup_script(SCRIPT, self.ALL, True)
        self.assertEqual(kept, SCRIPT)
        self.assertEqual(removed, [])

    def test_a_spacecraft_without_dtn_loses_both(self):
        kept, removed = prune_startup_script(SCRIPT, self.ALL, False)
        self.assertEqual(removed, ["bplib", "bpnode"])
        self.assertNotIn("bplib", names(kept))
        self.assertNotIn("bpnode", names(kept))
        self.assertEqual(names(kept), ["cryptolib", "io_lib", "cf", "adcs", "demo", "radio"])

    def test_component_pruning_still_follows_the_spacecraft_component_list(self):
        kept, removed = prune_startup_script(SCRIPT, {"adcs", "radio"}, True)
        self.assertEqual(removed, ["demo"])
        self.assertEqual(names(kept), ["cryptolib", "io_lib", "bplib", "cf", "bpnode", "adcs", "radio"])

    def test_dtn_and_components_are_independent(self):
        _, removed = prune_startup_script(SCRIPT, set(), False)
        self.assertEqual(sorted(removed), ["adcs", "bplib", "bpnode", "demo", "radio"])

    def test_comments_blank_lines_and_other_libraries_are_never_touched(self):
        kept, _ = prune_startup_script(SCRIPT, set(), False)
        self.assertIn("\n", kept)
        self.assertIn("! A comment that mentions bpnode and adcs.\n", kept)
        self.assertTrue(any(line.startswith("CFE_LIB, cryptolib") for line in kept))

    def test_the_shipped_startup_script_lists_bpnode_and_its_library_once(self):
        from pathlib import Path
        lines = (Path(__file__).resolve().parent.parent / "cfg/shire_defs/cpu1_cfe_es_startup.scr").read_text().splitlines(True)
        self.assertEqual(names(lines).count("bplib"), 1)
        self.assertEqual(names(lines).count("bpnode"), 1)
        self.assertLess(names(lines).index("bplib"), names(lines).index("bpnode"), "the library loads first")
        kept, removed = prune_startup_script(lines, self.ALL, False)
        self.assertEqual(removed, ["bplib", "bpnode"])


if __name__ == "__main__":
    unittest.main()
