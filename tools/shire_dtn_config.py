"""Delay and Disruption Tolerant Networking settings for a spacecraft's flight software.

A spacecraft runs NASA's BPNode (Bundle Protocol) only when its configuration has a `dtn:` block. The block
sets the node number, which BPLib bakes in at compile time, so the orchestrator renders it into a CMake file
for the flight software build. Startup script entries for BPNode are removed for spacecraft without the block.
"""
import math

MAX_NODE_ID = 2**32 - 1
DTN_KEYS = {"node_id"}
# Startup script entries that exist only on a spacecraft that has a `dtn:` block, by object type and name.
DTN_STARTUP_ENTRIES = {("CFE_LIB", "bplib"), ("CFE_APP", "bpnode")}
# Startup script applications that belong to the spacecraft's component list.
COMPONENT_APPS = ("adcs", "demo", "eps", "radio")


def normalize_dtn(config):
    """Returns the validated `dtn:` block, or None when a spacecraft does not run BPNode."""
    if config is None:
        return None
    if not isinstance(config, dict):
        raise ValueError("dtn must be a mapping")
    extra = sorted(set(config) - DTN_KEYS)
    if extra:
        raise ValueError(f"dtn has unknown key(s) {', '.join(map(repr, extra))}; allowed: {', '.join(sorted(DTN_KEYS))}")
    node_id = config.get("node_id")
    if isinstance(node_id, bool) or not isinstance(node_id, int) or not 1 <= node_id <= MAX_NODE_ID:
        raise ValueError(f"dtn node_id must be an integer in [1, {MAX_NODE_ID}]")
    return {"node_id": node_id}


def render_dtn_cmake(dtn):
    """The CMake file that gives the flight software build the node number."""
    return ("# Generated by tools/shire-orchestrator.py from the spacecraft's dtn: settings. Do not edit.\n"
            f"add_compile_definitions(BPLIB_LOCAL_EID_NODE_NUM={dtn['node_id']})\n")


def prune_startup_script(lines, enabled_components, dtn_enabled):
    """Drops startup entries for component applications the spacecraft does not enable, and for BPNode and
    its library when it has no `dtn:` block. Returns the kept lines and the names that were removed."""
    kept, removed = [], []
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("!"):
            kept.append(line)
            continue
        parts = [p.strip() for p in line.split(",")]
        kind, name = parts[0], parts[1] if len(parts) > 1 else None
        if (kind, name) in DTN_STARTUP_ENTRIES:
            keep = dtn_enabled
        elif kind == "CFE_APP" and name in COMPONENT_APPS:
            keep = name in enabled_components
        else:
            keep = True
        if keep:
            kept.append(line)
        else:
            removed.append(name)
    return kept, removed
